const drugById = new Map(DRUGS.map((d) => [d.id, d]))

export function getDrug(id: string): DrugInfo | undefined {
  return drugById.get(id)
}

export function drugsForDisease(disease: 'osteoporosis' | 'ra' | 'kneeOA'): DrugInfo[] {
  return DRUGS.filter((d) => d.disease.includes(disease))
}

/** 骨吸収抑制薬（歯科連携が必要な薬）か */
export function needsDentalCoordination(id: string): boolean {
  const d = drugById.get(id)
  if (!d) return false
  return ['bisphosphonate', 'denosumab', 'romosozumab'].includes(d.cls)
}

/** 投与期間の上限があり、終了後に逐次療法が必要な薬か */
export function needsSequentialTherapy(id: string): boolean {
  const d = drugById.get(id)
  if (!d) return false
  return ['teriparatide', 'abaloparatide', 'romosozumab'].includes(d.cls)
}
